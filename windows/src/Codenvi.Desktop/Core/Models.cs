namespace Codenvi.Desktop.Core;

#pragma warning disable CS8618
/// <summary>Local project (desktop is the source of truth for folder paths, Project.md §2).</summary>
public sealed class LocalProject
{
    public Guid Id { get; set; }
    public string Name { get; set; }
    public string FolderPath { get; set; }
    public string DevBranch { get; set; } = "codenvi-dev";
    public string PermissionMode { get; set; } = "acceptEdits";
    /// <summary>Space-separated Claude Code tool rules, e.g. "Read Edit Write Bash(npm test:*)".</summary>
    public string AllowedTools { get; set; } = "Read Edit Write Glob Grep";
    public int MaxTurns { get; set; } = 40;
    public int TimeoutMinutes { get; set; } = 60;
    public string? DefaultModel { get; set; }
    public string? DefaultEffort { get; set; }
    public int SortOrder { get; set; }
    public bool Paused { get; set; }
}

public sealed class LocalSession
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public string Name { get; set; }
    /// <summary>UUID passed to `claude --session-id` / `--resume`. Generated by Codenvi.</summary>
    public Guid ClaudeSessionId { get; set; }
    /// <summary>True once Claude Code created the transcript, so later jobs use --resume.</summary>
    public bool Started { get; set; }
    /// <summary>Set after a rollback; prefixed to the next prompt (Project.md §8.6).</summary>
    public string? RollbackNote { get; set; }
    public DateTime CreatedAt { get; set; }
}

public sealed class LocalJob
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public Guid SessionId { get; set; }
    public Guid PromptMessageId { get; set; }
    public string Status { get; set; }
    public string? ErrorCode { get; set; }
    public string? PromptPreview { get; set; }
    public DateTime ReceivedAt { get; set; }
    public DateTime? StartedAt { get; set; }
    public DateTime? FinishedAt { get; set; }
    public decimal? CostUsd { get; set; }
    public string? CommitHash { get; set; }
    public bool HasUncommittedChanges { get; set; }
}

public sealed class LocalCommit
{
    public Guid Id { get; set; }
    public Guid ProjectId { get; set; }
    public Guid? JobId { get; set; }
    public string GitHash { get; set; }
    public string Kind { get; set; }
    public string Message { get; set; }
    public int FilesChanged { get; set; }
    public int Insertions { get; set; }
    public int Deletions { get; set; }
    public Guid? RevertedBy { get; set; }
    public DateTime CreatedAt { get; set; }
}
#pragma warning restore CS8618

/// <summary>Values from the Settings screen (Project.md §8.4).</summary>
public sealed class AppSettings
{
    public bool StartWithWindows { get; set; }
    public bool MinimizeToTray { get; set; } = true;
    public int MaxParallelProjects { get; set; } = 2;
    public string GitAuthorName { get; set; } = "Codenvi";
    public string GitAuthorEmail { get; set; } = "codenvi@local";
    public string DefaultDevBranch { get; set; } = "codenvi-dev";
    public int StaleJobHours { get; set; } = 24;
    public bool DeleteTranscriptsOnClear { get; set; }
    public bool AutoSwitchBranch { get; set; }
    public bool DisclaimerAccepted { get; set; }
    public bool PauseAll { get; set; }
}
